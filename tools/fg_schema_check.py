#!/usr/bin/env python3
"""fg_schema_check — the input contract, checked against our own artifacts.

The verifier refuses bad values but accepted any shape. An agent integrating with this tool had no
machine-readable contract, only examples. This validates:

  * a claim against schemas/claim-0.1.json
  * a SourceRecord against schemas/source-record-0.1.json
  * a merged manifest against schemas/inventory-0.1.json
  * the sample bundle's claim against the claim schema

and then applies the same schemas to every artifact this repository generates, because a contract
that its own producer violates is a wish.

    python tools/fg_schema_check.py                 # check the fixtures
    python tools/fg_schema_check.py --self          # also check generated artifacts
    python tools/fg_schema_check.py --claim f.json  # check one file
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS = ROOT / "schemas"

try:
    from jsonschema import Draft202012Validator
except ImportError:  # pragma: no cover - the dependency is declared, not optional
    print("jsonschema is required: pip install jsonschema")
    sys.exit(2)


def load_schema(name):
    return json.loads((SCHEMAS / name).read_text(encoding="utf-8"))


def validate(doc, schema_name, label):
    validator = Draft202012Validator(load_schema(schema_name))
    errors = sorted(validator.iter_errors(doc), key=lambda e: list(e.absolute_path))
    out = []
    for e in errors[:6]:
        where = "/".join(str(p) for p in e.absolute_path) or "(root)"
        out.append(f"{label}: {where}: {e.message}")
    return out, len(errors)


def check_file(path, schema_name, label=None):
    label = label or path.name
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    return validate(doc, schema_name, label)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--self", action="store_true", help="also check artifacts generated by this repo")
    ap.add_argument("--claim")
    ap.add_argument("--inventory")
    ap.add_argument("--source")
    a = ap.parse_args()

    problems, checked = [], 0

    def run(path, schema, label=None):
        nonlocal checked
        p = Path(path)
        if not p.exists():
            problems.append(f"{p}: missing")
            return
        errs, _ = check_file(p, schema, label)
        checked += 1
        problems.extend(errs)

    if a.claim:
        run(a.claim, "claim-0.1.json", "claim")
    if a.inventory:
        run(a.inventory, "inventory-0.1.json", "inventory")
    if a.source:
        run(a.source, "source-record-0.1.json", "source")

    if a.self:
        for f in (ROOT / "fixtures").rglob("*.json"):
            name = f.name.lower()
            if "claim" in name or "probe" in str(f.parent).lower():
                run(f, "claim-0.1.json", f"fixture claim {f.name}")
        for f in (ROOT / "tools" / "_tmp").glob("*.json"):
            name = f.name.lower()
            if name.startswith("claim"):
                run(f, "claim-0.1.json", f"generated claim {f.name}")
            if name.startswith("m") and "claim" not in name:
                run(f, "inventory-0.1.json", f"generated manifest {f.name}")
            if name.startswith("s-") or name.startswith("g") or name.startswith("c2"):
                run(f, "source-record-0.1.json", f"generated source {f.name}")
        run(ROOT / "fixtures" / "sample-bundle" / "bundle.json", "bundle.json"
            if (SCHEMAS / "bundle.json").exists() else "claim-0.1.json", "sample bundle")

    print(f"artifacts checked: {checked}, problems: {len(problems)}")
    for p in problems[:12]:
        print(f"  {p}")
    print("RESULT:", "ok" if not problems else "fail")
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())

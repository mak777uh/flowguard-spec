#!/usr/bin/env python3
"""fg_open_questions — the counters in docs/34 must be computed, not typed.

`docs/34-OPEN-QUESTIONS.md` opens with "counters, so nobody argues with prose". By 2026-10-31 those counters
had drifted in four directions at once: it said 1 ADR (17 exist), 0 lines of product code (11 726 Python and
1 713 Rust), 0 measurements (109 metric rows carry a command) and 2/0 cards (72). A page whose job is to end
arguments had become the argument, which is the same defect the STATUS page had.

So the block between the markers is generated from the tree, and CI fails when it is stale:

    python tools/fg_open_questions.py           # rewrite the block
    python tools/fg_open_questions.py --check   # exit 1 when stale
"""
import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "34-OPEN-QUESTIONS.md"
BEGIN = "<!-- BEGIN counters (generated by tools/fg_open_questions.py; do not edit by hand) -->"
END = "<!-- END counters -->"


def lines_in(paths) -> int:
    total = 0
    for p in paths:
        try:
            total += len(p.read_text(encoding="utf-8", errors="ignore").splitlines())
        except OSError:
            continue
    return total


def count_cards() -> tuple[int, int]:
    cards = [p for p in sorted((ROOT / "lab" / "experiments").glob("*.md"))
             if p.name not in ("INDEX.md", "README.md") and "-" in p.name]
    ran = 0
    for p in cards:
        text = p.read_text(encoding="utf-8", errors="ignore")
        if re.search(r"(?m)^status:\s*completed", text) or re.search(r"(?m)^verdict:\s*(supports|refutes|inconclusive)", text):
            ran += 1
    return len(cards), ran


def count_metrics() -> int:
    text = (ROOT / "docs" / "METRICS.md").read_text(encoding="utf-8", errors="ignore")
    return len([l for l in text.splitlines() if re.match(r"^\|\s*\d+\s*\|", l)])


def kit_conformance() -> str:
    r = subprocess.run([sys.executable, str(ROOT / "lab" / "check-interop.py"), "--repo", str(ROOT)],
                       capture_output=True, text=True)
    m = re.search(r"kit conformance:\s*(\d+)/(\d+)", r.stdout)
    return f"{m.group(1)} / {m.group(2)}" if m else "?"


def claims_citing_missing_artifacts() -> int:
    text = (ROOT / "docs" / "CLAIMS.md").read_text(encoding="utf-8", errors="ignore")
    missing = set()
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        for token in re.findall(r"`([^`]+)`", line):
            if "://" in token or " " in token or "/" not in token:
                continue
            if not (ROOT / token).exists():
                missing.add(token)
    return len(missing)


def guards_in_ci() -> int:
    text = (ROOT / ".github" / "workflows" / "guards.yml").read_text(encoding="utf-8", errors="ignore")
    return len(re.findall(r"(?m)^\s{6}- name:", text))


def block() -> str:
    cards, ran = count_cards()
    adrs = len(list((ROOT / "lab" / "decisions").glob("*.md")))
    py = lines_in((ROOT / "tools").glob("*.py")) + lines_in((ROOT / "enumerators").rglob("*.py"))
    rs = lines_in((ROOT / "core-rs" / "src").glob("*.rs"))
    rows = [
        "| counter | value |",
        "|---|---|",
        f"| claims citing an artifact that does not exist | **{claims_citing_missing_artifacts()}** |",
        f"| experiment cards registered / run | **{cards} / {ran}** |",
        f"| ADRs | {adrs} |",
        f"| kit conformance | **{kit_conformance()}** |",
        f"| measurements produced by this repository | {count_metrics()} |",
        f"| lines of product code (`tools/` + `enumerators/` + `core-rs/src`) | {py:,} python + {rs:,} rust |".replace(",", " "),
        f"| guards in CI | {guards_in_ci()} |",
    ]
    return BEGIN + "\n\n" + "\n".join(rows) + "\n\n" + END


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    text = DOC.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("the counter markers are missing from docs/34-OPEN-QUESTIONS.md")
        return 2
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    fresh = head + block() + tail

    if fresh == text:
        print("counters: current")
        return 0
    if a.check:
        print("counters are stale — run python tools/fg_open_questions.py")
        return 1
    DOC.write_text(fresh, encoding="utf-8", newline="\n")
    print("counters rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""build-indexes — generate the three evidence indexes, and delete stale lines while doing it.

An index written by hand rots in both directions: a new file never appears, a deleted file stays. So the indexes
are generated, and `lab/check-evidence-reachability.py` fails in both directions too (a file with no line, a line
with no file).

    python lab/build-indexes.py            # rewrite the indexes
    python lab/build-indexes.py --check    # exit 1 if any index is stale
"""
import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

HEADER_CARDS = """# Experiment index — every card, one line each

Generated by `lab/build-indexes.py`; checked by `lab/check-evidence-reachability.py`. A card that is not in this
list is a card nobody will find, which is why the guard refuses it.

| card | hypothesis | verdict |
|---|---|---|
"""

HEADER_AUDIT = """# cross-audit — reviews exchanged with sibling projects

A file per review, named `YYYY-MM-DD-<reviewer>-reviews-<subject>.md`, plus our dispositions. Generated index;
checked by `lab/check-evidence-reachability.py`.

| file | |
|---|---|
"""


def tracked(prefix: str, pattern: str = "*.md") -> list[str]:
    out = subprocess.run(["git", "ls-files", f"{prefix}/{pattern}"], cwd=ROOT,
                         capture_output=True, text=True).stdout.split()
    return sorted(f for f in out if f)


def card_row(rel: str) -> str:
    text = (ROOT / rel).read_text(encoding="utf-8", errors="ignore")
    verdict = ""
    for line in text.splitlines()[:20]:
        if line.startswith("verdict:"):
            verdict = line.split(":", 1)[1].strip()
            break
    return f"| [{pathlib.Path(rel).stem}]({pathlib.Path(rel).name}) | `{pathlib.Path(rel).stem}` | {verdict} |"


def build_cards() -> str:
    rows = [card_row(f) for f in tracked("lab/experiments") if not f.endswith(("INDEX.md",))]
    return HEADER_CARDS + "\n".join(rows) + "\n"


def build_audit() -> str:
    rows = [f"| [{pathlib.Path(f).name}]({pathlib.Path(f).name}) | |" for f in tracked("cross-audit")
            if not f.endswith("README.md")]
    return HEADER_AUDIT + "\n".join(rows) + "\n"


def interop_section() -> str:
    files = [f for f in tracked("interop") if not f.endswith("README.md")]
    nested = [f for f in tracked("interop/verifiers") if not f.endswith("README.md")]
    lines = ["<!-- generated by lab/build-indexes.py: every note, one line each -->",
             "", "## Все заметки канала", ""]
    for f in files + nested:
        lines.append(f"- [`{f}`]({f})")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    targets = {
        ROOT / "lab" / "experiments" / "INDEX.md": build_cards(),
        ROOT / "cross-audit" / "README.md": build_audit(),
    }
    stale = []
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != content:
            stale.append(path)
            if not a.check:
                path.write_text(content, encoding="utf-8")

    # the interop index keeps its prose and gets its generated section replaced
    ip = ROOT / "interop" / "README.md"
    text = ip.read_text(encoding="utf-8") if ip.exists() else ""
    marker = "<!-- generated by lab/build-indexes.py: every note, one line each -->"
    section = interop_section()
    if marker in text:
        head = text.split(marker)[0].rstrip()
        new_text = head + "\n\n" + section
    else:
        new_text = text.rstrip() + "\n\n" + section
    if new_text != text:
        stale.append(ip)
        if not a.check:
            ip.write_text(new_text, encoding="utf-8")

    for path in stale:
        print(f"{'stale' if a.check else 'wrote'}: {path.relative_to(ROOT)}")
    print("RESULT:", "ok" if not (a.check and stale) else "fail")
    return 0 if not (a.check and stale) else 1


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""fg_report_html — one self-contained HTML page for a bundle, with no build step and no network.

Why not React, shadcn, Next, Nest or hono: those optimise for how fast an agent can build a UI, and they are good
at that. This page optimises for something else - a stranger must be able to read the artifact offline, with no
build, no CDN, no server, and no trust in whoever generated it. A single file with inline CSS and no JavaScript is
the smallest thing that satisfies that, and it is generated by the same stdlib-only toolset that produces the
verdict.

    python tools/fg_report_html.py --bundle fixtures/sample-bundle --out report.html

The page leads with the specific paths, not with the verdict - the usefulness study (docs/34, insight C) found
that general statements lose perceived value even when they are correct.
"""
import argparse
import html
import json
import pathlib
import subprocess
import sys

CSS = """
:root { color-scheme: light dark; --fg:#111; --bg:#fff; --mute:#555; --line:#ddd; --ok:#0a7; --bad:#b00; }
@media (prefers-color-scheme: dark) { :root { --fg:#eee; --bg:#111; --mute:#aaa; --line:#333; } }
body { font: 15px/1.5 -apple-system, Segoe UI, Roboto, sans-serif; margin: 2rem auto; max-width: 60rem;
       padding: 0 1rem; color: var(--fg); background: var(--bg); }
h1 { font-size: 1.4rem; margin-bottom: .2rem; }
h2 { font-size: 1.05rem; margin-top: 2rem; border-bottom: 1px solid var(--line); padding-bottom: .2rem; }
.mono { font-family: ui-monospace, Consolas, monospace; font-size: .9em; }
.mute { color: var(--mute); }
table { border-collapse: collapse; width: 100%; margin: .6rem 0; }
th, td { text-align: left; padding: .3rem .5rem; border-bottom: 1px solid var(--line); vertical-align: top; }
.ok { color: var(--ok); font-weight: 600; }
.bad { color: var(--bad); font-weight: 600; }
code { background: rgba(127,127,127,.15); padding: 0 .25em; border-radius: 3px; }
"""


def esc(x) -> str:
    return html.escape(str(x), quote=True)


def load(path: pathlib.Path):
    return json.loads(path.read_text(encoding="utf-8"))


def verdict_of(bundle_dir: pathlib.Path):
    """Ask the verifier itself; the page must not re-implement its arithmetic."""
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    r = subprocess.run([sys.executable, str(pathlib.Path(__file__).resolve().parent / "fg_bundle.py"),
                        "verify", "--bundle", str(bundle_dir)], capture_output=True, text=True)
    try:
        return json.loads(r.stdout)
    except Exception:  # noqa: BLE001
        return {"verdict": "UNKNOWN", "errors": [], "raw": (r.stdout or r.stderr)[:400]}


def claim_and_inventory(bundle_dir: pathlib.Path):
    bundle = load(bundle_dir / "bundle.json")
    claim = inv = None
    for digest in (bundle.get("objects") or {}):
        obj = bundle_dir / "objects" / digest
        if not obj.exists():
            continue
        try:
            doc = load(obj)
        except Exception:  # noqa: BLE001
            continue
        if isinstance(doc, dict) and "declared_level" in doc:
            claim = doc
        elif isinstance(doc, dict) and "paths" in doc:
            inv = doc
    return bundle, claim, inv


def paths_table(inv) -> str:
    rows = []
    for p in (inv or {}).get("paths", []):
        attr = (p.get("attribution") or {}).get("to") or "none"
        cls = "ok" if attr != "none" else "bad"
        rows.append(
            "<tr>"
            f"<td class='mono'>{esc(p.get('path_id', ''))}</td>"
            f"<td>{esc(p.get('kind', ''))}</td>"
            f"<td class='mono'>{esc(p.get('entry', ''))}</td>"
            f"<td class='mono'>{esc(p.get('target', ''))}</td>"
            f"<td class='{cls}'>{esc(attr)}</td>"
            "</tr>")
    if not rows:
        return "<p class='mute'>no paths in this inventory</p>"
    return ("<table><tr><th>path</th><th>kind</th><th>entry</th><th>target</th>"
            "<th>attributed to</th></tr>" + "".join(rows) + "</table>")


def render(bundle_dir: pathlib.Path) -> str:
    bundle, claim, inv = claim_and_inventory(bundle_dir)
    v = verdict_of(bundle_dir)
    status = v.get("verdict", "UNKNOWN")
    cls = "ok" if status == "SIGNED_AND_CONSISTENT" else "bad"
    address = v.get("address")
    if isinstance(address, dict):
        addr = address.get("recorded") or address.get("recomputed") or "—"
    else:
        addr = address or "—"

    n_paths = len((inv or {}).get("paths", []))
    attributed = sum(1 for p in (inv or {}).get("paths", [])
                     if (p.get("attribution") or {}).get("to"))
    coverage = (attributed / n_paths) if n_paths else 0.0

    claims = ""
    if claim:
        nc = ", ".join(claim.get("not_claimed") or []) or "—"
        claims = f"""
  <h2>What it claims, and what it refuses to claim</h2>
  <table>
    <tr><th>declared level</th><td class='mono'>{esc(claim.get('declared_level', '—'))}</td></tr>
    <tr><th>control point</th><td class='mono'>{esc(claim.get('declared_control_point', '—'))}</td></tr>
    <tr><th>evidence tier</th><td class='mono'>{esc(claim.get('evidence_tier', '—'))}</td></tr>
    <tr><th>not claimed</th><td class='mono'>{esc(nc)}</td></tr>
  </table>"""

    errors = v.get("errors") or []
    err_html = ("<p class='ok'>no refusals</p>" if not errors else
                "<table><tr><th>code</th><th>subject</th><th>expected</th><th>observed</th></tr>" +
                "".join(f"<tr><td class='mono'>{esc(e.get('code'))}</td><td>{esc(e.get('subject'))}</td>"
                        f"<td>{esc(e.get('expected'))}</td><td>{esc(e.get('observed'))}</td></tr>"
                        for e in errors) + "</table>")

    return f"""<!doctype html>
<meta charset="utf-8">
<title>FlowGuard — {esc(status)}</title>
<style>{CSS}</style>
<h1>FlowGuard report</h1>
<p class="mute mono">bundle {esc(addr)} · format {esc(bundle.get('bundle_version', '—'))}</p>
<p>Verdict: <span class="{cls}">{esc(status)}</span>
   <span class="mute">— a statement about this document, not about the system it describes</span></p>

<h2>The paths, first</h2>
<p>{n_paths} paths enumerated, <b>{attributed}</b> attributed to the declared control point
   (coverage <span class="mono">{coverage:.2f}</span>). Every row below is a way the target can be written.</p>
{paths_table(inv)}
{claims}

<h2>Refusals</h2>
{err_html}

<h2>What this page cannot tell you</h2>
<ul>
  <li>Whether the inventory is complete. A path that no enumerator saw is not on this page (<code>NC-01</code>).</li>
  <li>Whether anything outside the declared scope is safe (<code>NC-02</code>).</li>
  <li>Whether the parties whose signatures are attached had authority to attach them.</li>
</ul>
<p class="mute">Generated by <code>tools/fg_report_html.py</code> from the bundle alone — no network, no build step,
no JavaScript. Re-generate it from the same bundle and you must get the same bytes.</p>
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    page = render(pathlib.Path(a.bundle))
    pathlib.Path(a.out).write_text(page, encoding="utf-8")
    print(f"wrote {a.out} ({len(page)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

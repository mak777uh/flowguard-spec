#!/usr/bin/env python3
"""fg_dossier — one self-contained file to hand to an outside model.

The file is organised around **uncertainty**, not around achievements: what is not known, why the
answer matters, what evidence exists, and what would count as an answer. Numbers are injected from
the artifacts so the facts cannot drift; the uncertainty list is curated here, because deciding
*what is genuinely unknown* is the editorial act this file exists for.

    python tools/fg_dossier.py            # write DOSSIER.md
    python tools/fg_dossier.py --check    # exit 1 if stale
    python tools/fg_dossier.py --stdout
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "DOSSIER.md"


def front_matter(text):
    if not text.startswith("---"):
        return {}
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}
    fm = {}
    for line in parts[1].splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"')
    return fm


def metrics():
    rows = []
    for line in (ROOT / "docs" / "METRICS.md").read_text(encoding="utf-8").splitlines():
        if re.match(r"^\|\s*\d+\s*\|", line):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 3:
                rows.append((cells[0], cells[1], cells[2]))
    return rows


def cards():
    out = []
    for p in sorted((ROOT / "lab" / "experiments").glob("*.md")):
        fm = front_matter(p.read_text(encoding="utf-8"))
        if fm.get("id"):
            out.append(fm)
    return out


def readiness():
    try:
        r = subprocess.run([sys.executable, str(ROOT / "tools" / "fg_readiness.py")],
                           cwd=ROOT, capture_output=True, text=True, timeout=900)
        pct = re.search(r"core \(engine\): (\d+)%\s+product: (\d+)%\s+overall: (\d+)%", r.stdout)
        tier = re.search(r"tier:\s*(T\d)", r.stdout)
        return {"engine": pct.group(1) if pct else "?",
                "product": pct.group(2) if pct else "?",
                "overall": pct.group(3) if pct else "?",
                "tier": tier.group(1) if tier else "?"}
    except Exception:  # noqa: BLE001
        return {"engine": "?", "product": "?", "overall": "?", "tier": "?"}


def pick(m, needle):
    for n, what, value in m:
        if needle in what:
            return value
    return "?"


def _clip(text, n):
    """Cut a quote at a word boundary: a sentence ending mid-word is not a quote."""
    text = str(text)
    if len(text) <= n:
        return text
    cut = text[:n].rsplit(' ', 1)[0]
    return cut + ' …'


def build() -> str:
    m = metrics()
    cs = cards()
    r = readiness()
    refuted = [c for c in cs if c.get("verdict") == "refutes"]

    L = []
    A = L.append

    A("# Бриф: где в этом проекте неопределённость\n")
    A("*Файл сгенерирован из артефактов репозитория (`python tools/fg_dossier.py`). Числа взяты из журнала "
      "замеров, а не написаны руками. Нужен ответ по существу, не оценка проекта.*\n")
    A("**Что мне нужно от тебя.** Ниже десять мест, где я не знаю ответа, и не могу узнать его изнутри. По "
      "каждому: что известно фактически, что предполагается без достаточных оснований, какое решение зависит от "
      "ответа, и что будет считаться ответом. Если ответа нет — так и скажи: «нет свидетельства» тоже ответ.\n")

    A("## Что уже решено и не обсуждается\n")
    A("Это не темы для дискуссии, а входные данные — чтобы ты не тратил ответ на очевидное.\n")
    A("```")
    A("единица аттестации         поток, не система; «безопасность приложения» не заявляется никогда")
    A("артефакт                   scoped consistency attestation, не «подтверждение безопасности»")
    A("потребитель                ИИ-агент: JSON на вход, JSON на выход, без интерактива")
    A("подпись                    без двух якорей извне не значит ничего (проверено: 3 из 6 подмен проходили)")
    A("отказ                      машинный, с кодом; проза в not_claimed не принимается")
    A("ограничения                перечислены кодами NC-01…NC-11 и обязательны для уровня")
    A("```\n")
    A(f"Состояние, посчитанное из репозитория: ядро {r['engine']}%, продукт {r['product']}%, "
      f"общая {r['overall']}%, уровень {r['tier']}. Замеров: {len(m)}. Карточек экспериментов: {len(cs)}, "
      f"из них провальных: {len(refuted)}.\n")

    A("## Где неопределённость\n")

    A("### 1. Мои числа — свидетельство или демонстрация?\n")
    A(f"**Известно.** Обходы на посаженной фикстуре: {pick(m, 'recall on planted bypasses')}; точность строк "
      f"{pick(m, 'row precision')}; корпус мутантов — "
      f"{pick(m, 'D-1 detection')} обнаружения на 102 мутантах; на реальной публичной схеме (Pagila) "
      "инструмент нашёл 1 настоящую функцию с динамическим SQL за 0.4 с.\n")
    A("**Предполагается.** Что этих чисел достаточно, чтобы считать механизм проверенным.\n")
    A("**Почему это важно.** От этого зависит, что я публикую и каким тоном: «инструмент» или «инструмент, "
      "которому можно верить на чужой схеме».\n")
    A("**Вопрос.** Какая выборка сделала бы эти числа свидетельством: сколько реальных схем, какого размера, "
      "как отобранных? И что считается честным результатом на схеме, где обходов **ноль** — а это самый "
      "вероятный исход на практике?\n")

    A("### 2. Ложная причина исключения проходит\n")
    A("**Известно.** Исключение обязано назвать существующий путь, не может указывать в ядро и обязано нести "
      "причину. До этой починки утверждение, исключавшее выдуманный идентификатор, **проходило** — это "
      "измерено.\n")
    A("**Предполагается.** Что человек перечитает и заметит ложь.\n")
    A("**Почему это важно.** Сужение области — главный способ сделать отчёт красивым. Если причина не "
      "проверяется, продукт не масштабируется дальше одного аудитора.\n")
    A("**Вопрос.** Есть ли механизм, делающий ложную причину видимой или невыгодной автоматически? Может ли "
      "класс риска пути противоречить заявленной причине, и что делать с путями, чей класс неясен?\n")

    A("### 3. Веса риска — соглашение, а не измерение\n")
    A("**Известно.** Веса: деньги 5, личные данные 4, файлы 2, прочее 1, неопознанное 3 (никогда 0). Хеш "
      "политики публикуется в каждом вердикте.\n")
    A("**Предполагается.** Что такое взвешивание вообще осмысленно, а не создаёт видимость точности.\n")
    A("**Почему это важно.** Если веса не могут быть приняты третьей стороной, то `outside_weighted_risk` — "
      "язык для переговоров, и я обязан это написать вместо «измерения».\n")
    A("**Вопрос.** Известна ли практика, где веса остаточного риска принимает **третья сторона** и они живут "
      "дольше одного отчёта? Что именно делает их приемлемыми — регулятор, договор, отраслевая таблица, "
      "история? Если ответ «никак», так и скажи.\n")

    A("### 4. Знаменатель против свидетеля\n")
    A("**Известно.** Источники прав, вызовов и маршрутов перечисляют — они могут задавать знаменатель покрытия. "
      "Рантайм-источник наблюдает и **занижает счёт**: записи внутри хранимых процедур отдельными операторами "
      "в лог не попадают. Измерено: 3 из 3 прямых записей видны, 0 из 2 внутри функций.\n")
    A("**Предполагается.** Что такая граница проходит по всем технологиям.\n")
    A("**Вопрос.** Существует ли источник, который **и перечисляет, и наблюдает** — WAL-декодирование, "
      "`pgaudit`, eBPF, анализ бинарника — и может ли он ответить «сколько путей существует», а не «сколько "
      "сработало»? Назови технологию и на какой стороне границы она лежит.\n")

    A("### 5. Склейка источников по имени функции\n")
    A("**Известно.** Маршрут `/transfer/batch` объявляет вызов `transfer_batch`; граф вызовов знает, что тот "
      "доходит до контрольной точки. По отдельности ни один источник не может атрибутировать маршрут. Правило "
      "живёт в сборщике и записывает оба источника.\n")
    A("**Предполагается.** Что склейка по имени не создаёт ложных атрибуций.\n")
    A("**Вопрос.** Назови класс ошибок, который такая склейка создаёт (перегрузки, одинаковые имена в разных "
      "схемах, динамическая диспетчеризация), и как настоящие системы разрешают вызовы между слоями. Если "
      "ответ «только вручную» — тоже ответ.\n")

    A("### 6. Рост периметра и мёртвые пути\n")
    A("**Известно.** Появление нового пути блокирует повышение уровня, и исчезновение старого это не отменяет: "
      "замена — тоже изменение формы. Проверено на двух состояниях реальной базы: +1 путь → рост → повышение "
      "запрещено.\n")
    A("**Предполагается.** Что это правильная конвенция.\n")
    A("**Вопрос.** Не создаёт ли она стимул **не удалять** мёртвые пути, чтобы дельта выглядела спокойнее? Что "
      "сказал бы аудитор, у которого рефакторинг заменил один путь другим?\n")

    A("### 7. Изменит ли кто-нибудь своё решение из-за этого артефакта\n")
    A("**Известно.** Продуктовая половина готовности — 0%, и это не про код: нужен один названный человек, "
      "который скажет, какое своё решение он изменит. Форма на пять строк готова, заполняется за двадцать минут, "
      "и **шаблон даёт ноль баллов** — зачёт только за заполненные поля.\n")
    A("**Предполагается.** Что такой человек существует.\n")
    A("**Почему это важно.** Если десять разговоров дадут ноль, это ответ: продукт сужается до открытого "
      "инструмента, и это нормальный исход.\n")
    A("**Вопрос.** Кто это конкретно и какое решение меняется? Аудитор, меняющий объём работ; страховщик, "
      "меняющий исключение; протокол, ставящий условие на листинг; закупка, принимающая вендора. Если ты "
      "считаешь, что таких людей нет — скажи это прямо.\n")

    A("### 8. Кто подписывает принятие риска и чем рискует\n")
    A("**Известно.** Поле `risk_acceptance` зарезервировано в формате и не реализовано. Варианты: без подписи "
      "(продукт = инструмент), подпись со сферой доверия, подпись с возмещением.\n")
    A("**Почему это важно.** Без подписи артефакт нельзя продать тому, кому нужна возможность предъявить "
      "претензию, — а это большинство покупателей.\n")
    A("**Вопрос.** Как в известных практиках (SOC 2, страховой андеррайтинг, аудит бухгалтерской отчётности) "
      "устроен переход от «мы проверили» к «мы отвечаем»? Что именно подписывает сторона и чем ограничивает "
      "свою ответственность формально?\n")

    A("### 9. Агент — одновременно клиент и противник\n")
    A("**Известно.** Замыкание и политику выбирает тот, кто платит или запускает. Если это агент, у него есть "
      "интерес сузить границы: меньше путей — красивее отчёт. Механизмов против этого у меня нет, кроме "
      "пересчёта покрытия и обязательных кодов.\n")
    A("**Вопрос.** Что в формате или протоколе делает сужение **невыгодным или видимым**? Известны ли практики, "
      "где инструмент принимает вывод ИИ и не даёт ему сузить область проверки?\n")

    A("### 10. Что я не имею права утверждать, но хочу проверить\n")
    A("**Известно.** Все замеры прошли на схемах, где я контролировал постановку. На единственной чужой схеме "
      "(Pagila) результат скромный и настоящий: 1 функция с динамическим SQL, найденная за 0.4 с.\n")
    A("**Вопрос.** Какая минимальная проверка на чужой стороне дала бы право сказать «это работает не только на "
      "моих фикстурах»? Один прогон на чужой схеме? Два? Прогон, где владелец схемы сам проверил найденное?\n")

    A("## Формат ответа, который мне поможет\n")
    A("```")
    A("по каждому пункту:  ответ · свидетельство (практика, число, проект или «нет свидетельства») ·")
    A("                    что изменится в продукте · уверенность")
    A("в конце:             один главный вердикт одной фразой")
    A("```\n")
    A("**Бесполезно:** «выглядит солидно», «стоит подумать о безопасности», пересказ моего же текста.\n")
    A("**Полезно:** механизм (как делают, где именно, с каким результатом); класс ошибок, который конструкция "
      "не ловит; число, которое сделало бы утверждение свидетельством; прямое «нет свидетельства».\n")

    A("## Минимум деталей, если понадобится проверить\n")
    A("```")
    A("источники   grants (права, функции, триггеры) · pgcalls (граф вызовов PL/pgSQL) ·")
    A("            runtime (серверный лог) · routes (манифест маршрутов)")
    A("слияние     объединение по пути, конфликты, атрибуция через границу источников, дельта периметра")
    A("вердикт     пересчёт покрытия, 8 кодов отказа, потолки, взвешенный риск")
    A("бандл       fg-bundle/1, Ed25519, проверка только с двумя внешними якорями")
    A("")
    A("bash lab/round-check.sh          # стражи, негативные контроли, приёмочный набор, аудит")
    A("python tools/fg_readiness.py     # готовность из артефактов")
    A("python lab/e-m12-run.py          # 19 сценариев верификатора")
    A("```\n")

    if refuted:
        A("## Мои провалы — чтобы ты не тратил время на их поиск\n")
        for c in refuted:
            A(f"- **{c.get('id')}** — " + _clip(c.get('result', ''), 300))
        A("")
        A("Провалы не переписаны задним числом: карточка остаётся с вердиктом `refutes`, починка — отдельной "
          "карточкой.\n")

    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stdout", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.stdout:
        print(text)
        return 0
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("DOSSIER.md is stale — run python tools/fg_dossier.py")
            return 1
        print("DOSSIER.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

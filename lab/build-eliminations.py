#!/usr/bin/env python3
"""build-eliminations — the registry of ruled-out hypotheses, generated from the cards that refuted them.

Taken from `mak777uh/-` (morphogenesis), whose `docs/eliminations.md` keeps every ruled-out hypothesis with the
artifact that killed it and **what would revive it**. This repository had `refutes` cards but no registry, so a
refuted idea could quietly return — which is exactly what a registry prevents.

The rule that makes it more than a list: **an entry without a revival condition is not an elimination, it is an
opinion.** A hypothesis you cannot say how to revive was not killed by evidence.

    python lab/build-eliminations.py            # rewrite docs/ELIMINATIONS.md
    python lab/build-eliminations.py --check    # exit 1 if it is stale
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CARDS = ROOT / "lab" / "experiments"
OUT = ROOT / "docs" / "ELIMINATIONS.md"

HEADER = """# Ruled out — hypotheses this repository has refuted, and what would revive them

Generated by `lab/build-eliminations.py` from the cards whose verdict is `refutes`; checked by
`lab/check-eliminations.py`. Hand-written parts live in `lab/elimination-revival.tsv` and are never overwritten.

The rule that makes this more than a list: **an entry without a revival condition is not an elimination, it is an
opinion.** If you cannot say how the hypothesis could come back, it was not killed by evidence.

| card | what was refuted | verdict | what would revive it |
|---|---|---|---|
"""


def cards() -> list[dict]:
    out = []
    for path in sorted(CARDS.glob("*.md")):
        if path.name in ("INDEX.md", "README.md") or "-" not in path.name:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        m = re.search(r"^verdict:\s*(\S+)", text, re.M)
        verdict = m.group(1) if m else "none"
        if verdict != "refutes":
            continue
        cid = path.name.split("-")[0] + "-" + path.name.split("-")[1]
        hyp = ""
        mh = re.search(r"^hypothesis:\s*(\S+)", text, re.M)
        if mh:
            hyp = mh.group(1)
        out.append({"card": cid, "file": path.name, "hypothesis": hyp, "verdict": verdict})
    return out


def revival_map() -> dict[str, str]:
    path = ROOT / "lab" / "elimination-revival.tsv"
    if not path.exists():
        return {}
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) >= 2:
            out[parts[0].strip()] = parts[1].strip()
    return out


def build() -> str:
    rev = revival_map()
    rows = []
    for c in cards():
        r = rev.get(c["card"], "")
        if not r:
            r = "**missing — add it to lab/elimination-revival.tsv**"
        rows.append(f"| [{c['card']}](../lab/experiments/{c['file']}) | `{c['hypothesis'] or '—'}` | {c['verdict']} | {r} |")
    return HEADER + "\n".join(rows) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    content = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current == content:
        print("ELIMINATIONS.md is current")
        return 0
    if a.check:
        print("ELIMINATIONS.md is stale — run python lab/build-eliminations.py")
        return 1
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({content.count(chr(10)) - 8} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

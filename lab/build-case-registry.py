#!/usr/bin/env python3
"""build-case-registry — cases/REGISTRY.md is generated from the folders, never typed.

A registry kept by hand rots the first week nobody reads it. This one is rebuilt from the case files, and
`--check` fails when a case exists that the table does not name, or the table names a case that is gone.

    python lab/build-case-registry.py           # rewrite cases/REGISTRY.md
    python lab/build-case-registry.py --check   # exit 1 when stale
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CASES = ROOT / "cases"
OUT = CASES / "REGISTRY.md"
BEGIN = "<!-- BEGIN registry (generated by lab/build-case-registry.py) -->"
END = "<!-- END registry -->"
NAME = re.compile(r"^\d{3}-[a-z0-9-]+$")


def cases():
    out = []
    for d in sorted(p for p in CASES.iterdir() if p.is_dir()):
        if d.name == "TEMPLATE" or not NAME.match(d.name):
            continue
        readme = d / "README.md"
        if not readme.exists():
            continue
        text = readme.read_text(encoding="utf-8")
        head = next((l for l in text.splitlines() if l.startswith("# ")), "")
        verdict = next((l.split("**")[-1].strip() for l in text.splitlines()
                        if l.strip().startswith("**Verdict:**")), "?")
        sentence = head[2:].strip()
        sentence = re.sub(r"^\d{3}\s*[—-]\s*", "", sentence)
        out.append((d.name, verdict, sentence))
    return out


def block() -> str:
    rows = ["| case | verdict | what was checked |", "|---|---|---|"]
    for name, verdict, sentence in cases():
        rows.append(f"| [{name}]({name}/README.md) | {verdict} | {sentence} |")
    if len(rows) == 2:
        rows.append("| — | — | no cases yet |")
    return BEGIN + "\n\n" + "\n".join(rows) + "\n\n" + END


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    body = block()
    header = ("# Case registry\n\n"
              "Generated from the folders by `lab/build-case-registry.py`; `--check` fails when it is stale.\n"
              "A verdict of `not confirmed` is published here exactly like `confirmed`.\n\n")
    fresh = header + body + "\n"

    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current == fresh:
        print(f"cases: {len(cases())}, registry current")
        return 0
    if a.check:
        print("cases/REGISTRY.md is stale — run python lab/build-case-registry.py")
        return 1
    OUT.write_text(fresh, encoding="utf-8", newline="\n")
    print(f"cases: {len(cases())}, registry rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
